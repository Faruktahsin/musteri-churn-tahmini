import numpy as np
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer

from sklearn.linear_model import LogisticRegression
from sklearn.neighbors import KNeighborsClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix
)


# --------------------------------------------------
# 1. Veri setini oluşturma
# --------------------------------------------------

np.random.seed(42)

n = 200

df = pd.DataFrame({
    "yas": np.random.randint(18, 70, n),
    "gelir": np.random.randint(15000, 100000, n),
    "abonelik_suresi": np.random.randint(1, 61, n),
    "destek_talebi_sayisi": np.random.randint(0, 8, n),
    "sehir": np.random.choice(
        ["Istanbul", "Ankara", "Izmir", "Bursa"],
        n
    ),
    "uyelik_tipi": np.random.choice(
        ["Basic", "Standard", "Premium"],
        n
    )
})


# Churn değerini müşteri özellikleriyle ilişkili şekilde oluşturalım.

risk = (
    (df["abonelik_suresi"] < 12) * 0.30
    + (df["destek_talebi_sayisi"] >= 4) * 0.35
    + (df["uyelik_tipi"] == "Basic") * 0.20
    + (df["gelir"] < 30000) * 0.15
)

churn_probability = np.clip(0.10 + risk, 0, 0.90)

df["churn"] = np.random.binomial(
    1,
    churn_probability
)


# --------------------------------------------------
# 2. Veri setini inceleme
# --------------------------------------------------

print("VERİ SETİNİN İLK 5 SATIRI")
print(df.head())

print("\nVeri setinin boyutu:")
print(df.shape)

print("\nChurn dağılımı:")
print(df["churn"].value_counts())

print("\nChurn oranları:")
print(df["churn"].value_counts(normalize=True).round(2))


# --------------------------------------------------
# 3. Eksik değer kontrolü
# --------------------------------------------------

print("\nEKSİK DEĞERLER")
print(df.isnull().sum())


# --------------------------------------------------
# 4. Yeni öznitelik oluşturma
# --------------------------------------------------

df["destek_talebi_var_mi"] = (
    df["destek_talebi_sayisi"] > 0
).astype(int)

print("\nYeni oluşturulan özellik:")
print(
    df[
        [
            "destek_talebi_sayisi",
            "destek_talebi_var_mi"
        ]
    ].head()
)


# --------------------------------------------------
# 5. Bağımsız ve hedef değişkenler
# --------------------------------------------------

X = df.drop("churn", axis=1)
y = df["churn"]


# --------------------------------------------------
# 6. Train, validation ve test ayırma
# --------------------------------------------------

X_train_val, X_test, y_train_val, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

X_train, X_val, y_train, y_val = train_test_split(
    X_train_val,
    y_train_val,
    test_size=0.25,
    random_state=42,
    stratify=y_train_val
)

print("\nVERİ SETİ BÖLÜNMESİ")
print("Train:", X_train.shape)
print("Validation:", X_val.shape)
print("Test:", X_test.shape)


# --------------------------------------------------
# 7. Sayısal ve kategorik sütunlar
# --------------------------------------------------

sayisal_sutunlar = [
    "yas",
    "gelir",
    "abonelik_suresi",
    "destek_talebi_sayisi",
    "destek_talebi_var_mi"
]

kategorik_sutunlar = [
    "sehir",
    "uyelik_tipi"
]


# --------------------------------------------------
# 8. Veri ön işleme
# --------------------------------------------------

sayisal_islemler = Pipeline([
    (
        "eksik_deger",
        SimpleImputer(strategy="median")
    ),
    (
        "olcekleme",
        StandardScaler()
    )
])

kategorik_islemler = Pipeline([
    (
        "eksik_deger",
        SimpleImputer(strategy="most_frequent")
    ),
    (
        "one_hot",
        OneHotEncoder(handle_unknown="ignore")
    )
])

on_isleme = ColumnTransformer([
    (
        "sayisal",
        sayisal_islemler,
        sayisal_sutunlar
    ),
    (
        "kategorik",
        kategorik_islemler,
        kategorik_sutunlar
    )
])


# --------------------------------------------------
# 9. Modeller
# --------------------------------------------------

logistic_model = Pipeline([
    (
        "on_isleme",
        on_isleme
    ),
    (
        "model",
        LogisticRegression(max_iter=1000)
    )
])

knn_model = Pipeline([
    (
        "on_isleme",
        on_isleme
    ),
    (
        "model",
        KNeighborsClassifier(n_neighbors=5)
    )
])


modeller = {
    "Logistic Regression": logistic_model,
    "KNN": knn_model
}


# --------------------------------------------------
# 10. Validation sonuçlarını karşılaştırma
# --------------------------------------------------

validation_sonuclari = {}

print("\nVALIDATION SONUÇLARI")

for model_adi, model in modeller.items():

    model.fit(
        X_train,
        y_train
    )

    tahmin = model.predict(
        X_val
    )

    accuracy = accuracy_score(
        y_val,
        tahmin
    )

    validation_sonuclari[model_adi] = accuracy

    print(
        model_adi,
        "- Accuracy:",
        round(accuracy, 4)
    )


# --------------------------------------------------
# 11. En iyi modeli seçme
# --------------------------------------------------

en_iyi_model_adi = max(
    validation_sonuclari,
    key=validation_sonuclari.get
)

en_iyi_model = modeller[
    en_iyi_model_adi
]

print(
    "\nValidation sonucuna göre en iyi model:",
    en_iyi_model_adi
)


# Train ve validation verilerini birlikte kullanarak
# seçilen modeli yeniden eğitiyoruz.

en_iyi_model.fit(
    X_train_val,
    y_train_val
)


# --------------------------------------------------
# 12. Test seti değerlendirmesi
# --------------------------------------------------

test_tahmin = en_iyi_model.predict(
    X_test
)

accuracy = accuracy_score(
    y_test,
    test_tahmin
)

precision = precision_score(
    y_test,
    test_tahmin,
    zero_division=0
)

recall = recall_score(
    y_test,
    test_tahmin,
    zero_division=0
)

f1 = f1_score(
    y_test,
    test_tahmin,
    zero_division=0
)

cm = confusion_matrix(
    y_test,
    test_tahmin
)


print("\nTEST SONUÇLARI")

print(
    "Seçilen model:",
    en_iyi_model_adi
)

print("\nConfusion Matrix:")
print(cm)

print(
    "\nAccuracy:",
    round(accuracy, 4)
)

print(
    "Precision:",
    round(precision, 4)
)

print(
    "Recall:",
    round(recall, 4)
)

print(
    "F1-score:",
    round(f1, 4)
)


# --------------------------------------------------
# 13. Sonuç yorumu
# --------------------------------------------------

print("\nSONUÇ YORUMU")

print(
    "Validation sonuçlarına göre",
    en_iyi_model_adi,
    "modeli daha başarılı olmuştur."
)

if en_iyi_model_adi == "Logistic Regression":

    print(
        "Veri setindeki churn ilişkilerinin büyük ölçüde "
        "basit yapıda olması Logistic Regression modelinin "
        "başarılı olmasını sağlamış olabilir."
    )

else:

    print(
        "Benzer müşteri özelliklerine sahip kişilerin churn "
        "davranışlarının yakın olması KNN modelinin daha "
        "başarılı olmasını sağlamış olabilir."
    )

print(
    "Sonuçları değerlendirirken accuracy dışında precision, "
    "recall ve F1-score değerlerinin de birlikte incelenmesi "
    "gerektiğini düşünüyorum."
)